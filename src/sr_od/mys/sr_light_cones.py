# 名称反查索引：模块加载时构建一次（进程内缓存）；170 名称唯一由单测锁定。
LIGHT_CONE_BY_NAME: dict[str, LightConeDef] = {
    cone.name: cone for cone in LIGHT_CONES
}

# tid → 定义索引：mys equip id 反查与图标寻址用。
LIGHT_CONE_BY_TID: dict[int, LightConeDef] = {
    cone.tid: cone for cone in LIGHT_CONES
}

#: 图标归档相对路径公式（项目 assets 根起）；170 把全量，见模块 docstring。
_LIGHT_CONE_ICON_REL_TEMPLATE = 'assets/game_data/light_cone_icons/lightcone_{tid}.webp'


def icon_webp_rel_path(tid: int) -> str:
    """光锥 tid → 图标 webp 的项目相对路径。

    纯公式寻址不查存在性（零 IO 纪律）；文件归档见模块 docstring。
    """
    return _LIGHT_CONE_ICON_REL_TEMPLATE.format(tid=tid)


def resolve_light_cone(name: str) -> LightConeDef | None:
    """光锥名 → 定义（miss 返回 None，不抛异常）。"""
    return LIGHT_CONE_BY_NAME.get(name)


def resolve_cone_by_tid(tid: int) -> LightConeDef | None:
    """mys equip id（tid）→ 光锥定义（miss 返回 None，不抛异常）。"""
    return LIGHT_CONE_BY_TID.get(tid)
