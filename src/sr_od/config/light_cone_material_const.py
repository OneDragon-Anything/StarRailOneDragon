    """光锥名 → 该光锥晋阶需要的特殊材料清单(经验书/信用点之外的专属类);
    表外光锥返回空列表。"""
    return [material for material, cones in _LIGHT_CONE_MATERIAL_DATA.items()
            if cone_name in cones]
