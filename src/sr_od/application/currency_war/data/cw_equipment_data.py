@dataclass(frozen=True)
class Equipment:
    """单件装备(官方规范数据)。"""
    name: str           # 规范名(• 统一 ·)
    category: str       # 官方分类名直落:进阶装备/特权装备/星徽/餐品改件/列车改件/宝钻/固有装备;另含派生值「简易装备」
    effect: str         # 效果纯文本(desc 剥富文本标签;\n 为字面换行)
    stacking: bool      # 效果可叠加(「可叠加/叠加N层」→True;文本推断,实机抽检另账)
